const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = process.cwd();
const checkOnly = process.argv.includes('--check');
const idPattern = /^OS-TH-[0-9]{4}$/;
const siteBase = 'https://edulinked-coder.github.io/Osteosarcoma-Therapeutic-Hypotheses-Open-Machine-Readable-Research/';
let stale = false;

const esc = (value) => String(value ?? '').replace(/[&<>"']/g, (c) => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const safeExternalUrl = (value) => {
  const url = new URL(String(value));
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error('Unsupported public source URL scheme: ' + url.protocol);
  return esc(url.toString());
};
const readText = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const readJson = (rel) => JSON.parse(readText(rel));
const writeProjection = (rel, content) => {
  const target = path.join(root, rel);
  const normalized = content.endsWith('\n') ? content : content + '\n';
  if (checkOnly) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== normalized) {
      console.error('STALE GENERATED PROJECTION: ' + rel);
      stale = true;
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, normalized, 'utf8');
  console.log('Generated ' + rel);
};

const hypothesisDirs = fs.readdirSync(path.join(root, 'hypotheses'), { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && idPattern.test(entry.name))
  .map((entry) => entry.name)
  .sort();

if (hypothesisDirs.length === 0) throw new Error('No canonical hypothesis directories found.');

const records = hypothesisDirs.map((id) => {
  const rel = `hypotheses/${id}/hypothesis.json`;
  const object = readJson(rel);
  if (object.hypothesis_id !== id) throw new Error(`${rel} hypothesis_id does not match its stable directory.`);
  const digest = crypto.createHash('sha256').update(JSON.stringify(object)).digest('hex');
  return { id, rel, object, digest };
});

const evidencePathsFor = (h) => {
  const refs = [...(h.supporting_evidence || []), ...((h.contradictory_evidence || {}).items || [])]
    .map((item) => item.evidence_id)
    .filter(Boolean)
    .map((id) => `evidence-bindings/${id}.json`);
  return [...new Set(refs)].sort();
};

const latestUpdatedAt = records.map(({ object }) => object.provenance.updated_at).sort().at(-1);
const index = {
  schema_version: '1.0.0',
  generated_by: 'scripts/render-public-research.js',
  generated_at: latestUpdatedAt,
  source: 'Canonical public hypothesis objects in /hypotheses/. Generated by scripts/render-public-research.js.',
  clinical_use_boundary: 'Research hypotheses only. Not medical advice, treatment recommendations, dosing instructions or claims of patient benefit.',
  hypothesis_count: records.length,
  hypotheses_requiring_review: records.filter(({ object }) => object.review_state.scientific_review_required && object.review_state.status !== 'reviewed').length,
  hypotheses: records.map(({ object: h }) => ({
    schema_version: h.schema_version,
    hypothesis_id: h.hypothesis_id,
    title: h.title,
    plain_language_summary: h.plain_language_summary,
    hypothesis_statement: h.hypothesis_statement,
    evidence_stage: h.evidence_stage,
    review_state: h.review_state,
    publication_path: `hypotheses/${h.hypothesis_id}/`,
    canonical_object_path: `hypotheses/${h.hypothesis_id}/hypothesis.json`,
    evidence_binding_paths: evidencePathsFor(h),
    last_evidence_update: h.provenance.updated_at,
    clinical_use: h.clinical_use
  }))
};
writeProjection('indexes/hypotheses.json', JSON.stringify(index, null, 2));

